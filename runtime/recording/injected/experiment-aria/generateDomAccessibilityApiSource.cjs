const { buildSync } = require('esbuild')
const { writeFileSync } = require('node:fs')
const { join } = require('node:path')

const bundled = buildSync({
  bundle: true,
  entryPoints: [join(require.resolve('dom-accessibility-api'), '..', 'index.mjs')],
  format: 'iife',
  globalName: 'domAccessibilityApi',
  legalComments: 'none',
  minify: true,
  platform: 'browser',
  write: false,
}).outputFiles[0].text
const source = `/*! dom-accessibility-api v0.7.1 | MIT License | Copyright 2020 Sebastian Silbermann */\n${bundled}`
const quotedSource = `'${source.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('\r', '\\r').replaceAll('\n', '\\n').replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029')}'`
const moduleSource = `export { domAccessibilityApiSource }\n\n// Generated by generateDomAccessibilityApiSource.cjs.\nconst domAccessibilityApiSource =\n  ${quotedSource}\n`

writeFileSync(join(__dirname, 'domAccessibilityApiSource.ts'), moduleSource)
